/**
 * Strict Territorial & EEZ Boundary Validator for India
 * Excludes sovereign foreign territory of Pakistan, Afghanistan, central Myanmar, deep Tibet, and Bangladesh interior
 */
export function isWithinIndianTerritory(lat: number, lng: number): boolean {
  // Global bounding box for Indian subcontinent territory + Andaman & Lakshadweep
  if (lat < 6.5 || lat > 37.5 || lng < 68.1 || lng > 97.5) {
    return false;
  }

  // 1. Pakistan / Indus Basin West Border:
  // North of 32.5°N (J&K border) must be east of 74.2°E
  if (lat >= 32.5 && lng < 74.2) return false;
  // Punjab / Himachal border (30.0°N to 32.5°N) must be east of 73.8°E
  if (lat >= 30.0 && lat < 32.5 && lng < 73.8) return false;
  // North Rajasthan / Sindh border (27.5°N to 30.0°N) must be east of 70.8°E
  if (lat >= 27.5 && lat < 30.0 && lng < 70.8) return false;
  // Central/South Rajasthan / Sindh border (24.5°N to 27.5°N) must be east of 69.8°E
  if (lat >= 24.5 && lat < 27.5 && lng < 69.8) return false;
  // Gujarat / Rann of Kutch / Sir Creek border (23.5°N to 24.5°N) must be east of 68.3°E
  if (lat >= 23.5 && lat < 24.5 && lng < 68.3) return false;
  // Saurashtra coast & Arabian sea
  if (lat >= 21.0 && lat < 23.5 && lng < 68.8) return false;

  // 2. Offshore Arabian Sea (west of mainland coast, allowing Lakshadweep islands):
  if (lat < 21.0 && lng < 72.5) {
    // Lakshadweep archipelago bounds (8.0°N–14.0°N, 71.5°E–74.2°E)
    if (lat >= 8.0 && lat <= 14.0 && lng >= 71.5 && lng <= 74.2) {
      return true;
    }
    return false;
  }

  // 3. Tibet / China northern border ridge:
  if (lat > 35.5 && lng < 77.0) return false;
  if (lat > 36.5) return false;
  if (lat >= 31.5 && lat <= 34.0 && lng > 79.5) return false;

  // 4. Nepal Interior (exclude central Nepal territory, keep UP/Bihar/Uttarakhand):
  if (lat > 27.5 && lat <= 30.2 && lng > 81.2 && lng < 87.8) {
    return false;
  }

  // 5. Bangladesh Interior (keep West Bengal, Assam, Meghalaya, Tripura, Mizoram):
  if (lat > 22.3 && lat < 25.0 && lng > 88.9 && lng < 91.5) {
    return false;
  }

  // 6. Myanmar Interior:
  if (lat >= 21.5 && lat <= 26.5 && lng > 94.5) {
    if (lat < 25.5 && lng > 93.8) return false;
    if (lat >= 25.5 && lng > 95.2) return false;
  }

  return true;
}
